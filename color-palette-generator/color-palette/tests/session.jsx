import React from 'react';
import TestRenderer, { act } from 'react-test-renderer';
import assert from 'node:assert/strict';
import { AuthProvider, useAuth } from '../src/context/AuthContext';
import { PaletteProvider, usePalettes } from '../src/context/PaletteContext';
import { controls } from '../src/lib/supabase';
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
globalThis.fetch = async () => ({ ok:true, json:async () => ({ colors:Array.from({length:5},()=>({hex:{value:'#123456'}})) }) });
let state;
function Probe() { state = usePalettes(); return null; }
function Scope() { const {user}=useAuth(); return <PaletteProvider key={user?.id ?? 'guest'}><Probe /></PaletteProvider>; }
let root;
await act(async()=>{root=TestRenderer.create(<AuthProvider><Scope /></AuthProvider>);});
assert.match((await state.savePalette('Ocean')).error,/Sign in/);
await act(async()=>controls.emit('SIGNED_IN',{user:{id:'alice'}}));
await act(async()=>controls.loads.shift()({data:[{id:'a',name:'Alice',colors:['#123456']}],error:null}));
assert.equal(state.savedPalettes[0].name,'Alice');
let pending;
await act(async()=>{ pending=state.savePalette('New palette'); });
await act(async()=>controls.emit('SIGNED_OUT',null));
assert.equal(state.savedPalettes.length,0);
await act(async()=>controls.saves.shift()({data:{id:'late',name:'Late',colors:['#123456']},error:null}));
assert.match((await pending).error,/session changed/);
assert.equal(state.savedPalettes.length,0);
await act(async()=>controls.emit('SIGNED_IN',{user:{id:'alice'}}));
const oldLoad=controls.loads.shift();
await act(async()=>controls.emit('SIGNED_IN',{user:{id:'bob'}}));
await act(async()=>oldLoad({data:[{id:'private',name:'Private'}],error:null}));
assert.equal(state.savedPalettes.length,0);
await act(async()=>controls.loads.shift()({data:null,error:{message:'Offline'}}));
assert.match(state.savedError,/Could not load/);
await act(async()=>state.reloadSaved());
await act(async()=>controls.loads.shift()({data:[],error:null}));
assert.equal(state.savedError,'');
let result;
await act(async()=>{pending=state.savePalette('Ocean');});
await act(async()=>controls.saves.shift()({data:{id:'b',name:'Ocean',colors:['#123456']},error:null}));
result=await pending;
assert.equal(result.id,'b');
assert.equal(state.savedPalettes[0].name,'Ocean');
assert.match((await state.savePalette('OCEAN')).error,/already exists/);
await act(async()=>root.unmount());
console.log('PASS: signed-out saves blocked, save/load after account switch ignored, load retry, successful save, duplicate validation.');
